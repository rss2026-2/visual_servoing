def find_avg_score(results):
    """
    Finds the average scoring of a result

    :param results: A list of tuples. Each tuple stores the original image
    path name and the scoring each algorithm got for that image.

    Each score is in the range [0,1] (1 being higher signal),
    """
    return sum(entry[1] for entry in results) / len(results)

def find_variance_score(results):
    """
    Finds the variance in scoring of a result

    :param results: A list of tuples. Each tuple stores the original image
    path name and the scoring each algorithm got for that image.

    Each score is in the range [0,1] (1 being higher signal),
    """

    mean = find_avg_score(results)
    return sum(entry[1]**2 - mean**2 for entry in results) / len(results)

